from decimal import Decimal, InvalidOperation

from django.views.generic import TemplateView

from services.api_client import ApiClientError, api_get

class HomeView(TemplateView):
    template_name = "core/home.html"


class DashboardView(TemplateView):
    template_name = "core/dashboard.html"

    def get_context_data(self, **kwargs):
        context = super().get_context_data(**kwargs)
        context["api_error"] = None
        context["kpi_cards"] = []

        try:
            kpis = api_get("/kpis")
        except ApiClientError as exc:
            context["api_error"] = str(exc)
            return context

        context["kpi_cards"] = [
            {
                "label": "Total sales",
                "value": self.format_number(kpis.get("total_sales_count")),
                "description": "Number of sales transactions.",
            },
            {
                "label": "Total quantity sold",
                "value": self.format_number(kpis.get("total_quantity")),
                "description": "Total units sold across all transactions.",
            },
            {
                "label": "Total revenue",
                "value": self.format_number(kpis.get("total_revenue")),
                "description": "Revenue generated by all sales.",
            },
            {
                "label": "Promo sales",
                "value": self.format_number(kpis.get("promo_sales_count")),
                "description": "Sales transactions linked to a promotion.",
            },
            {
                "label": "Promo revenue",
                "value": self.format_number(kpis.get("promo_revenue")),
                "description": "Revenue generated by promotional sales.",
            },
            {
                "label": "Promo sales share",
                "value": self.format_percentage(kpis.get("promo_sales_share")),
                "description": "Share of sales transactions linked to promotions.",
            },
            {
                "label": "Average order value",
                "value": self.format_number(kpis.get("average_order_value")),
                "description": "Average revenue per sales transaction.",
            },
        ]

        return context

    @staticmethod
    def format_number(value):
        if value is None:
            return "N/A"

        try:
            return f"{Decimal(str(value)):,.2f}"
        except (InvalidOperation, ValueError):
            return str(value)

    @staticmethod
    def format_percentage(value):
        if value is None:
            return "N/A"

        try:
            return f"{Decimal(str(value)) * Decimal('100'):.2f}%"
        except (InvalidOperation, ValueError):
            return str(value)



